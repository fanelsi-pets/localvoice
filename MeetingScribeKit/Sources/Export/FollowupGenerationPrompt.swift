import Foundation

/// Язык follow-up, который просят у модели (SPEC.md §3.6): русский или украинский.
public enum FollowupLanguage: String, CaseIterable, Codable, Sendable, Hashable {
  case ru
  case uk

  public var title: String {
    switch self {
    case .ru: String(localized: "Русский")
    case .uk: String(localized: "Українська")
    }
  }
}

/// Промпт генерации follow-up для модели (локальной или провайдера хоста): подробная инструкция владельца
/// проекта — фиксировать решения, поручения и открытые вопросы без домыслов, с таймкодами и обязательным
/// блоком ```meeting-followup, который читает `FollowupParser`. Текст инструкции — русский для обоих языков,
/// вступление задаёт язык документа. Транскрипт (TranscribeFull без собственной инструкции экспорта)
/// прилагается в конце.
public enum FollowupGenerationPrompt {
  public static func render(language: FollowupLanguage, transcript: String) -> String {
    [intro(language), body, closing, transcript].joined(separator: "\n\n")
  }

  /// Имя файла по формату из инструкции: `[YYYY-MM-DD]_[Проект]_follow-up_имена_и_поручения.md`.
  public static func fileName(date: Date?, project: String?, language: FollowupLanguage) -> String {
    let dateText: String
    if let date {
      let formatter = DateFormatter()
      formatter.locale = Locale(identifier: "en_US_POSIX")
      formatter.timeZone = .current
      formatter.dateFormat = "yyyy-MM-dd"
      dateText = formatter.string(from: date)
    } else {
      dateText = language == .uk ? "дата-не-вказана" : "дата-не-указана"
    }
    let projectText =
      (project ?? "")
      .replacingOccurrences(of: "/", with: "-")
      .replacingOccurrences(of: ":", with: "-")
      .trimmingCharacters(in: .whitespacesAndNewlines)
    let suffix = language == .uk ? "follow-up_імена_та_доручення" : "follow-up_имена_и_поручения"
    let parts = [dateText, projectText, suffix].filter { !$0.isEmpty }
    return parts.joined(separator: "_") + ".md"
  }

  private static func intro(_ language: FollowupLanguage) -> String {
    switch language {
    case .ru:
      return """
        Подготовь подробный follow-up по приложенной расшифровке встречи на русском языке. Выдай результат \
        целиком в Markdown одним ответом: без вступлений и пояснений вне документа, первая строка — заголовок \
        уровня 1. Соблюдай указанную ниже структуру и порядок разделов.
        """
    case .uk:
      return """
        Підготуй докладний follow-up за доданою розшифровкою зустрічі українською мовою. Увесь документ — \
        заголовки розділів, назви колонок таблиць і текст — пиши українською; структуру та порядок розділів, \
        описані нижче російською, збережи, переклавши заголовки. Видай результат цілком у Markdown одним \
        повідомленням: без вступів і пояснень поза документом, перший рядок — заголовок рівня 1. Імена, цитати \
        й таймкоди зберігай як у джерелі.
        """
    }
  }

  private static let closing = """
    ## Формат выдачи

    Выдай весь документ в Markdown в ответе целиком. Ниже прилагается расшифровка встречи.
    """

  static let body = """
    Главная задача — точно зафиксировать, к чему пришли участники, что нужно сделать, кому это поручено и какие вопросы остались открытыми. Документ должен быть понятен человеку, который не присутствовал на встрече.

    ## Правила работы с источником

    1. Прочитай всю расшифровку до конца. Если обсуждение возвращается к одному вопросу, проследи, как менялась позиция, и зафиксируй итоговую договорённость.
    2. Используй только предоставленные материалы. Не переноси факты и решения из других встреч, если я прямо этого не попросил.
    3. Не фантазируй. Не добавляй собственные рекомендации, задачи, исполнителей, сроки, цифры или выводы о готовности продукта.
    4. Различай:
       - принятое рабочее решение;
       - поручение или явно принятое обязательство;
       - предложение, гипотезу или предпочтение;
       - демонстрацию существующего состояния или прототипа;
       - открытый вопрос;
       - отменённый или заменённый вариант.
    5. Решением считай явно принятую договорённость, которая не была отменена или оставлена спорной позднее. Сам факт, что вариант предложили, показали или не раскритиковали, не означает его принятия. Реплика «да» или «обсудили» сама по себе недостаточна без понятного контекста согласия.
    6. Согласованный принцип и его неподтверждённые параметры разделяй. Например, «ввести лимит» может быть решением, а обсуждавшаяся сумма — ещё нет.
    7. Не называй эффективность доказанной, если на встрече не приводили результаты проверки. Согласование рабочей группой не приравнивай к утверждению руководством.
    8. Указывай полные имена из расшифровки. Не угадывай фамилии, должности и соответствие голосов. Если имя неизвестно, сохраняй обозначение спикера.
    9. Назначай ответственного только при явном поручении или принятом обязательстве. Автор идеи или участник обсуждения не становится автоматически исполнителем.
    10. Если работу поручили команде, укажи команду. Если исполнителя не назначили, напиши «Ответственный не назначен». Не превращай неопределённое «нам нужно» в персональную задачу.
    11. Сохраняй степень определённости сроков: «предложено», «ориентир», «начать», «до следующей встречи». Относительные сроки считай от даты встречи, а не от текущего дня. Не превращай неделю или начало месяца в точный дедлайн.
    12. У каждого решения, поручения и открытого вопроса указывай таймкод или несколько таймкодов основания. Не выдумывай их. Если таймкодов нет, пиши «Таймкод отсутствует».
    13. Неразборчивые фрагменты и противоречия не достраивай. Отметь, что именно нельзя достоверно установить.
    14. Не ограничивай подробное резюме искусственно: для длинной встречи раскрой все существенные темы. При этом убирай бытовые отступления, повторы и разговорный шум.
    15. Все обязательные разделы сохраняй даже при отсутствии данных. Вместо выдуманного наполнения пиши «Не зафиксировано» или «Не обсуждалось». Количество решений, задач и вопросов определяется содержанием встречи.

    ## Обязательная структура документа

    # Follow-up · [Проект или тема] · [Дата встречи] · Имена и поручения

    В начале укажи:

    - **Ключ встречи:** технический идентификатор вида `[project]_[YYYY-MM-DD]_[recording-id]`. Используй доступные данные; недостающие части опусти. Отметь, что ключ сформирован для документа.
    - **Проект / тема:** из материалов.
    - **Дата:** дата встречи; если отсутствует — «Не указана».
    - **Длительность:** если известна.
    - **Источник:** название предоставленной записи или расшифровки.
    - **Статус:** что представляет собой результат встречи по источнику, без предположения о финальном согласовании.

    Добавь короткое пояснение: рабочие решения отделены от предложений; неназначенные исполнители и неподтверждённые сроки не додумывались.

    ## Кто и что должен сделать

    Поставь этот раздел перед резюме: это главный оперативный блок.

    | Ответственный | Что сделать | Ожидаемый результат | Срок, названный на встрече | Таймкод |
    |---|---|---|---|---|

    Правила таблицы:

    - Используй полные имена.
    - Для совместного поручения указывай всех названных исполнителей.
    - Разделяй разные поручения одному человеку на отдельные строки.
    - Ожидаемый результат формулируй только в пределах поручения. Не придумывай дополнительный документ, расчёт или отчёт.
    - Если результат отдельно не уточняли, пиши «Отдельно не уточнён».
    - Не представляй порученную работу как уже выполненную.
    - Здесь размещай задачи с названным исполнителем или командой. Неназначенные задачи вынеси в отдельный подраздел ниже.

    ### Какие решения нужно отразить в дальнейшей работе

    Кратко перечисли принятые решения, которые определяют дальнейшие действия. Укажи таймкоды.

    Связывай их с исполнителями только в пределах уже порученной работы. Не создавай новых назначений.

    ### Что ещё нужно решить — ответственный не назначен

    Перечисли необходимые дальнейшие вопросы и действия, для которых на встрече не назначили владельца. Не назначай его самостоятельно.

    ## Участники

    Перечисли имена из расшифровки. Роли указывай только при наличии в источнике.

    ## 1. Короткое резюме

    Напиши 5–7 содержательных предложений:

    - зачем собрались;
    - что обсуждали;
    - к чему пришли;
    - что осталось нерешённым;
    - какие следующие шаги договорились сделать;
    - каков статус дальнейшего согласования, если это обсуждалось.

    Не включай в резюме предложения как состоявшиеся решения.

    ## 2. Ключевые выводы — актуальная картина для быстрого погружения

    Дай нумерованный список основных выводов.

    В каждом пункте:
    - короткая формулировка;
    - необходимое объяснение;
    - ограничения или нерешённые параметры;
    - таймкоды.

    Раздел должен передавать актуальную картину после встречи. Если вывод описывает показанное состояние, а не принятое решение, прямо это обозначь.

    ## 3. Принятые рабочие решения

    Оформи каждое решение отдельно:

    ### D01. [Формулировка решения]

    **Основание:** [таймкод или несколько таймкодов].
    **Точка фиксации:** [реплика, в которой договорённость явно принята; если единственной точки нет, так и укажи].

    [Что именно согласовано, в каких границах и какие параметры ещё не определены.]

    Продолжай нумерацию D02, D03 и далее.

    Не включай предложения, спорные варианты и неподтверждённые цифры. Не объединяй в одно решение согласованную часть и гипотезу без явного разделения статусов.

    ## 4. Подробное резюме по темам

    Разбей разговор на смысловые темы с подзаголовками:

    ### 4.1. [Название темы]
    ### 4.2. [Название темы]

    Названия и количество подразделов определяются содержанием встречи.

    Для каждой темы объясни:
    - исходный вопрос или проблему;
    - существенные варианты и аргументы;
    - что выяснили;
    - какой вариант приняли, отложили или отвергли;
    - какие зависимости и ограничения остались;
    - что это означает для дальнейшей работы в пределах сказанного участниками.

    Указывай таймкоды. Организуй материал по темам, а не как пересказ каждой реплики. Если позиция менялась, поясни, какой более ранний вариант заменён итоговым.

    ## 5. Задачи на будущее с названными исполнителями

    Составь полный реестр поручений:

    | ID | Что сделать | Ответственный | Срок / ориентир | Основание |
    |---|---|---|---|---|
    | A01 | ... | ... | ... | ... |

    Используй A01, A02 и далее.

    Этот реестр и начальная таблица «Кто и что должен сделать» должны совпадать по составу поручений, исполнителям и срокам. Не добавляй сюда задачи, возникшие только из твоего анализа.

    ## 6. Открытые вопросы

    Оформи каждый вопрос отдельно:

    ### Q01. [Формулировка вопроса]

    [Что осталось неопределённым, какие варианты обсуждались и почему вопрос нельзя считать закрытым.]

    **Ответственный за проработку:** [только если назначен; иначе «Не назначен»].
    **Срок:** [только если назван; иначе «Не указан»].
    **Основание:** [таймкоды].

    Продолжай нумерацию Q02, Q03 и далее.

    Включай вопросы, отложенные решения, неутверждённые параметры и противоречия, сохранившиеся к концу встречи. Не добавляй общие вопросы «на всякий случай».

    ## 7. Что не следует считать принятым решением

    | Обсуждавшийся вариант | Итоговый статус |
    |---|---|

    Включи существенные предложения, примерные цифры, отменённые варианты и идеи будущего развития, которые легко ошибочно принять за договорённость. По возможности укажи таймкоды.

    Не повторяй каждый открытый вопрос: выдели прежде всего места с риском неверного прочтения.

    ## 8. Машиночитаемый блок

    В самом конце документа добавь один блок с языком `meeting-followup`. Внутри должен находиться только валидный JSON следующей структуры:

    {
      "decisions": [
        {
          "text": "Решение с необходимыми ограничениями",
          "timestamp": "HH:MM:SS"
        }
      ],
      "actions": [
        {
          "text": "Поручение; при необходимости — относительный срок или интервал",
          "owner": "Полное имя или несколько имён для совместного поручения",
          "due": "YYYY-MM-DD"
        }
      ],
      "questions": [
        {
          "text": "Открытый вопрос и существенная неопределённость"
        }
      ],
      "summary": "То же короткое резюме из раздела 1 одной строкой"
    }

    Правила JSON:
    - Открывающая строка блока — ровно три обратные кавычки и слово meeting-followup на той же строке (не json), закрывающая — три обратные кавычки; блок в документе один.
    - Состав решений, задач и вопросов должен соответствовать текстовым разделам.
    - `timestamp` — таймкод явной фиксации решения; если его невозможно установить, используй `null`.
    - `owner` — полное имя, названная команда или несколько имён; если исполнитель не установлен, используй `null`.
    - `due` — только однозначно установленная точная дата. Для интервала, приблизительного срока или отсутствующей даты используй `null`, сохранив формулировку срока в `text`.
    - Для отсутствующих элементов используй пустые массивы.
    - Не добавляй комментарии внутри JSON.

    ## Проверка перед выдачей

    Проверь:
    - прочитана ли вся встреча, включая финальные уточнения;
    - не попали ли гипотезы и заменённые варианты в решения;
    - подтверждаются ли имена, поручения и сроки источником;
    - не выданы ли примерные числа за утверждённые параметры;
    - совпадают ли две таблицы задач и JSON;
    - существуют ли указанные таймкоды;
    - сохранены ли все обязательные разделы;
    - валиден ли JSON.
    """
}
