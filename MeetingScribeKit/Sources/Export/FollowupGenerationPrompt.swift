import Foundation

/// Язык follow-up, который просят у модели (SPEC.md §3.6): русский или украинский.
public enum FollowupLanguage: String, CaseIterable, Codable, Sendable, Hashable {
  case ru
  case uk

  public var title: String {
    switch self {
    case .ru: String(localized: "Русский")
    case .uk: String(localized: "Українська")
    }
  }
}

/// Промпты follow-up для модели (локальной, провайдера хоста или внешней — через TranscribeFull).
///
/// Документ строится по темам встречи, как его пишет человек, который на ней был: «Главное» —
/// несколько итогов, затем раздел на каждую существенную тему с позициями сторон и тем, как
/// договорились, открытые вопросы, таблица задач и следующие шаги. Инструкция написана целиком на языке
/// документа: русская инструкция с украинским вступлением давала документ вперемешку на двух языках.
/// Служебных блоков нет — follow-up сохраняется в историю проекта как есть.
public enum FollowupGenerationPrompt {
  /// Промпт генерации: инструкция плюс расшифровка (TranscribeFull без собственной инструкции).
  public static func render(language: FollowupLanguage, transcript: String) -> String {
    [instruction(language), transcript].joined(separator: "\n\n")
  }

  /// Инструкция без расшифровки: её же TranscribeFull кладёт в конец экспорта для внешней модели.
  public static func instruction(_ language: FollowupLanguage) -> String {
    switch language {
    case .ru: russian
    case .uk: ukrainian
    }
  }

  /// Точный перевод готового follow-up на другой язык: структура, пункты и факты остаются теми же.
  public static func translation(of followup: String, to language: FollowupLanguage) -> String {
    let instruction: String
    switch language {
    case .ru:
      instruction = """
        Переведи приведённый ниже follow-up встречи на русский язык. Это точный перевод, а не пересказ: \
        сохрани смысл, порядок разделов и пунктов, разметку Markdown (заголовки, списки, жирный текст, \
        таблицы) и все факты, цифры, даты, сроки и формулировки договорённостей. Ничего не добавляй \
        и не сокращай. Имена людей передай в привычном русском написании (Іван Мінін → Иван Минин), \
        названия компаний, продуктов и сервисов не меняй. Выдай только переведённый документ — без \
        вступления, пояснений и обрамления в блок кода.
        """
    case .uk:
      instruction = """
        Переклади наведений нижче follow-up зустрічі українською мовою. Це точний переклад, а не \
        переказ: збережи зміст, порядок розділів і пунктів, розмітку Markdown (заголовки, списки, жирний \
        текст, таблиці) та всі факти, цифри, дати, терміни й формулювання домовленостей. Нічого не \
        додавай і не скорочуй. Імена людей передай у звичному українському написанні (Иван Минин → \
        Іван Мінін), назви компаній, продуктів і сервісів не змінюй. Видай лише перекладений документ — \
        без вступу, пояснень і обгортання в блок коду.
        """
    }
    return instruction + "\n\n---\n\n" + followup
  }

  /// Ответ модели без обёрток: модели иногда заворачивают документ в ```markdown, а ответы на старую
  /// инструкцию TranscribeFull заканчиваются служебным блоком ```meeting-followup — он больше не нужен.
  public static func cleanedAnswer(_ answer: String) -> String {
    var text = answer.trimmingCharacters(in: .whitespacesAndNewlines)
    if let block = text.range(of: "```meeting-followup", options: .backwards) {
      text = String(text[..<block.lowerBound]).trimmingCharacters(in: .whitespacesAndNewlines)
    }
    var lines = text.components(separatedBy: "\n")
    if let first = lines.first, first.hasPrefix("```"), lines.count > 1,
      lines.last?.trimmingCharacters(in: .whitespaces) == "```"
    {
      lines.removeFirst()
      lines.removeLast()
      text = lines.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
    }
    return text
  }

  /// Имя файла: `[YYYY-MM-DD]_[Проект]_follow-up_имена_и_поручения.md`.
  public static func fileName(date: Date?, project: String?, language: FollowupLanguage) -> String {
    let dateText: String
    if let date {
      let formatter = DateFormatter()
      formatter.locale = Locale(identifier: "en_US_POSIX")
      formatter.timeZone = .current
      formatter.dateFormat = "yyyy-MM-dd"
      dateText = formatter.string(from: date)
    } else {
      dateText = language == .uk ? "дата-не-вказана" : "дата-не-указана"
    }
    let projectText =
      (project ?? "")
      .replacingOccurrences(of: "/", with: "-")
      .replacingOccurrences(of: ":", with: "-")
      .trimmingCharacters(in: .whitespacesAndNewlines)
    let suffix = language == .uk ? "follow-up_імена_та_доручення" : "follow-up_имена_и_поручения"
    let parts = [dateText, projectText, suffix].filter { !$0.isEmpty }
    return parts.joined(separator: "_") + ".md"
  }

  static let russian = """
    Подготовь follow-up по приложенной расшифровке рабочей встречи. Весь документ — заголовки, \
    подписи, таблица и текст — на русском языке. Выдай его целиком в Markdown одним ответом: первая \
    строка — заголовок уровня 1, без вступлений, пояснений и обрамления в блок кода.

    Читатель — руководитель или коллега, который на встрече не был. За пять минут он должен понять, \
    что обсуждали, кто какую позицию занимал и почему, о чём договорились, кто что делает и что \
    осталось открытым. Пиши как участник встречи, который делает заметки для команды: конкретно, \
    по-деловому, без канцелярита и общих слов.

    ## Как работать с расшифровкой

    1. Прочитай расшифровку целиком до конца. Если к вопросу возвращались, проследи, как менялась \
    позиция, и фиксируй итог.
    2. Сохраняй конкретику — именно её теряет плохой follow-up: кто что сказал, цифры, сроки, названия, \
    причины и аргументы. Позиции приписывай участникам по имени: «[Имя]: технически задача несложная, \
    но нужна логика списка». Если участники представляют разные компании или команды, \
    показывай позицию каждой стороны.
    3. Вес темы определяй по встрече: сколько времени ей уделили и дошли ли до решения. Мимолётное \
    упоминание не раздувай в отдельный раздел и не выноси в «Главное». Не делай вывод о важности \
    темы из того, что она звучит в названии проекта или встречи.
    4. Каждый факт упоминай один раз — в разделе своей темы. Не повторяй одну и ту же мысль в разных \
    разделах и не вплетай одну тему (партнёра, риск, ограничение) в каждый пункт. «Главное», \
    «Открытые вопросы» и «Задачи» — короткие выжимки, а не пересказ тематических разделов.
    5. Используй только сказанное на встрече. Ничего не добавляй от себя: ни рекомендаций, ни задач, \
    ни исполнителей, ни сроков, ни цифр, ни оценок.
    6. Различай решение, поручение, предложение, мнение и открытый вопрос. Решение — то, о чём явно \
    договорились; предложенный, показанный или не раскритикованный вариант решением не становится. \
    Согласованный принцип отделяй от неутверждённых параметров.
    7. Исполнитель задачи — только тот, кому явно поручили или кто сам взялся; автор идеи не становится \
    исполнителем автоматически. Поручили команде — укажи команду; исполнителя нет — «Не назначен».
    8. Сроки передавай так, как их назвали, с их степенью определённости: «1–2 дня», «до следующей \
    встречи», «после релиза». Не превращай «на неделе» в точную дату. Срок не назвали — \
    «Не обсуждался».
    9. Имена — как в расшифровке; фамилии, должности и принадлежность к компании не угадывай. \
    Безымянных участников называй так, как они обозначены в расшифровке.
    10. Неразборчивые места и противоречия не достраивай. Бытовые отступления, повторы и разговорный \
    шум убирай. В тексте не используй таймкоды и служебные пометки, не пиши о том, как составлен \
    документ.

    ## Структура документа

    # [Проект или стороны] · [тема встречи]

    Follow-up встречи — [дата встречи в виде ДД.ММ.ГГГГ] · [в нескольких словах — о чём встреча]; \
    [длительность в минутах, например «52 мин»]

    ## Главное

    От трёх до шести пунктов — главные итоги в порядке важности, по одному на самые существенные \
    темы. Каждый пункт: короткий жирный тезис с точкой, затем одно-два предложения — к чему пришли, \
    кто что делает дальше.

    ## [Название темы]

    Отдельный раздел на каждую существенную тему встречи, названный по её сути («Онбординг новых \
    продавцов», а не «Обсуждение»). Темы — в порядке важности, а не в порядке реплик. \
    Внутри — маркированный список, каждый пункт начинается с жирной метки с точкой: \
    **Позиция [стороны или участника].**, **Предложение.**, **Технический контекст.**, \
    **Ограничения.**, **Цифры.** — какие подходят по смыслу. Последний пункт темы, если по ней \
    договорились, — **Как договорились.** Сколько тем — решает содержание встречи: часовая встреча \
    обычно даёт четыре-семь тем, короткую не раздувай.

    ## Открытые вопросы

    Маркированный список вопросов, которые остались без ответа или отложены, — по одному \
    предложению, без повторения аргументов из тем. Если таких нет — одна строка «Не осталось».

    ## Задачи

    | Задача | Ответственный | Срок |
    |---|---|---|

    Одна строка — одно поручение. Ответственный — имя (и сторона в скобках, если на встрече были \
    разные компании), несколько исполнителей — через запятую. Если поручений не было — вместо таблицы \
    строка «Поручений не было».

    ## Следующие шаги

    Один короткий абзац: что происходит дальше и в каком порядке — только из сказанного на встрече.
    """

