import Foundation

/// Язык follow-up, который просят у модели (SPEC.md §3.6): русский или украинский.
public enum FollowupLanguage: String, CaseIterable, Codable, Sendable, Hashable {
  case ru
  case uk

  public var title: String {
    switch self {
    case .ru: String(localized: "Русский")
    case .uk: String(localized: "Українська")
    }
  }
}

/// Промпт генерации follow-up для модели (локальной или провайдера хоста): документ в стиле аналитической
/// записки по образцу владельца проекта — «Главный вывод», что зафиксировали, решения, таблица действий,
/// открытые вопросы и ближайшая повестка; без идентификаторов и таймкодов в тексте. Служебный блок
/// ```meeting-followup модель добавляет после документа: его читает `FollowupParser`, а интерфейс
/// прячет (`FollowupParser.split`). Текст инструкции — русский для обоих языков, вступление задаёт язык
/// документа. Транскрипт (TranscribeFull без собственной инструкции экспорта) прилагается в конце.
public enum FollowupGenerationPrompt {
  public static func render(language: FollowupLanguage, transcript: String) -> String {
    [intro(language), body, closing, transcript].joined(separator: "\n\n")
  }

  /// Имя файла по формату из инструкции: `[YYYY-MM-DD]_[Проект]_follow-up_имена_и_поручения.md`.
  public static func fileName(date: Date?, project: String?, language: FollowupLanguage) -> String {
    let dateText: String
    if let date {
      let formatter = DateFormatter()
      formatter.locale = Locale(identifier: "en_US_POSIX")
      formatter.timeZone = .current
      formatter.dateFormat = "yyyy-MM-dd"
      dateText = formatter.string(from: date)
    } else {
      dateText = language == .uk ? "дата-не-вказана" : "дата-не-указана"
    }
    let projectText =
      (project ?? "")
      .replacingOccurrences(of: "/", with: "-")
      .replacingOccurrences(of: ":", with: "-")
      .trimmingCharacters(in: .whitespacesAndNewlines)
    let suffix = language == .uk ? "follow-up_імена_та_доручення" : "follow-up_имена_и_поручения"
    let parts = [dateText, projectText, suffix].filter { !$0.isEmpty }
    return parts.joined(separator: "_") + ".md"
  }

  private static func intro(_ language: FollowupLanguage) -> String {
    switch language {
    case .ru:
      return """
        Подготовь подробный follow-up по приложенной расшифровке встречи на русском языке. Выдай результат \
        целиком в Markdown одним ответом: без вступлений и пояснений вне документа, первая строка — заголовок \
        уровня 1. Соблюдай описанную ниже структуру и порядок разделов.
        """
    case .uk:
      return """
        Підготуй докладний follow-up за доданою розшифровкою зустрічі українською мовою. Увесь документ — \
        заголовки розділів, назви колонок таблиці й текст — пиши українською; структуру та порядок розділів, \
        описані нижче російською, збережи. Заголовки розділів українською: «Головний висновок», \
        «Що зафіксували», «Результати та рішення зустрічі», «Дії», «Відкриті питання та ризики», \
        «Найближчий порядок денний»; колонки таблиці — «Дія», «Власник», «Термін», «Результат»; порожній \
        розділ — «Не обговорювалося», відсутній виконавець — «Не призначено». Видай результат цілком у \
        Markdown одним повідомленням: без вступів і пояснень поза документом, перший рядок — заголовок \
        рівня 1. Імена та цитати зберігай як у джерелі.
        """
    }
  }

  private static let closing = """
    ## Формат выдачи

    Выдай весь документ в Markdown в ответе целиком, служебный блок — в самом конце ответа. Ниже прилагается \
    расшифровка встречи.
    """

  static let body = """
    Это документ для руководителя и команды, которые не были на встрече: за несколько минут он должен дать им картину — что решили, что и кому предстоит сделать, что осталось открытым и где риски. Пиши как аналитическую записку: конкретно, по существу, без канцелярита, без пересказа реплик и без служебных пометок.

    ## Правила работы с источником

    1. Прочитай всю расшифровку до конца. Если к вопросу возвращались, проследи, как менялась позиция, и фиксируй итоговую договорённость.
    2. Используй только приложенные материалы. Ничего не добавляй от себя: ни рекомендаций, ни задач, ни исполнителей, ни сроков, ни цифр, ни выводов о готовности продукта.
    3. Различай принятое решение, поручение или явное обязательство, предложение или гипотезу, демонстрацию текущего состояния и открытый вопрос. Решение — явно принятая договорённость, которую позже не отменили и не оставили спорной; сам факт, что вариант предложили, показали или не раскритиковали, не делает его принятым.
    4. Согласованный принцип и его неподтверждённые параметры разделяй: «ввести лимит» может быть решением, а обсуждавшаяся сумма — ещё нет. Примерные цифры не выдавай за утверждённые, а согласование рабочей группой — за утверждение руководством.
    5. Имена пиши как в расшифровке, полностью. Не угадывай фамилии, должности и соответствие голосов; если имя неизвестно, сохраняй обозначение спикера.
    6. Владельца действия указывай только при явном поручении или принятом обязательстве; автор идеи не становится исполнителем автоматически. Если поручили команде — укажи команду; если исполнителя нет — «Не назначен». Не превращай «нам нужно» в личную задачу.
    7. Сроки передавай с их степенью определённости: «ориентир», «предложено», «до следующей встречи». Относительные сроки считай от даты встречи, а не от текущего дня. Не превращай «на неделе» или «в начале месяца» в точную дату.
    8. Неразборчивые фрагменты и противоречия не достраивай — отметь, что установить не удалось. Бытовые отступления, повторы и разговорный шум убирай.
    9. В тексте документа не используй идентификаторы вроде D01, A01, Q01 и таймкоды. Не добавляй разделы самопроверки, пояснения о методике, «ключ встречи» и оговорки о том, что документ сформирован автоматически.
    10. Все обязательные разделы сохраняй в заданном порядке. Если для раздела нет материала — одна строка «Не обсуждалось» вместо выдуманного наполнения. Объём определяется содержанием встречи: для длинной встречи раскрой все существенные темы, короткую не раздувай.

    ## Обязательная структура документа

    # Follow-up — [Проект или тема встречи]

    **Встреча:** [дата], [длительность, если известна]
    **Цель:** [одно предложение: зачем собрались]

    ## Главный вывод

    Два-три абзаца: в чём суть проекта или обсуждения и на какой оно стадии; какая у него сильная сторона или базовая ценность; какие главные риски и ограничения видны по итогам встречи. Это самое важное место документа — без общих слов.

    ## Что зафиксировали

    Название раздела можно уточнить по теме встречи (например, «Что зафиксировали по продукту»). Разбей материал на смысловые подтемы с подзаголовками уровня 3 и маркированными списками: что выяснили, какие варианты обсуждали, что приняли, отложили или отвергли, какие зависимости и ограничения остались. Если позиция менялась, назови итоговую и отметь, какой прежний вариант заменён. Организуй по темам, а не по порядку реплик.

    ## Результаты и решения встречи

    Нумерованный список принятых договорённостей. Каждый пункт начинается с короткого жирного заголовка с точкой, затем одно-два предложения: что именно согласовано, в каких границах, какие параметры ещё не определены. Предложения, гипотезы и неподтверждённые цифры сюда не попадают — им место в открытых вопросах.

    ## Действия

    Таблица поручений:

    | Действие | Владелец | Срок | Результат |
    |---|---|---|---|

    Правила таблицы: одна строка — одно поручение; владелец — полное имя, несколько имён через « + » или команда, «Не назначен», если исполнителя нет; срок — как назван на встрече, с его степенью определённости («до 18.09», «ориентир — до запуска», «постоянно»); результат — что должно появиться в пределах поручения, без придуманных документов и отчётов, «Отдельно не уточнён», если его не обсуждали. Порученную работу не представляй выполненной.

    ## [Тематические разделы — при необходимости]

    Если материал встречи даёт основания, добавь один-два раздела, которые помогут читателю действовать: например, «Что можно говорить» и «Что пока нельзя обещать», «Ограничения MVP», «Доказательная база». Только из сказанного участниками. Если оснований нет — раздел не добавляй.

    ## Открытые вопросы и риски

    Нумерованный список. Каждый пункт — короткий жирный заголовок с точкой и пояснение: что не определено, какие варианты обсуждались и почему вопрос нельзя считать закрытым; ответственный и срок проработки — только если названы. Сюда же — отложенные решения, неутверждённые параметры и места, которые легко ошибочно принять за договорённость.

    ## Ближайшая повестка

    Нумерованный список того, что договорились сделать или обсудить на следующей встрече, включая решения, которые нужно принять к названной дате. Только из сказанного участниками; если следующие шаги не обсуждались — «Не обсуждалось».

    ## Служебный блок для приложения

    После документа, без заголовка и пояснений, добавь один блок: открывающая строка — ровно три обратные кавычки и слово meeting-followup на той же строке (не json), затем только валидный JSON, затем закрывающая строка из трёх обратных кавычек. Читателю этот блок не показывается: приложение забирает из него решения, задачи и вопросы в память проекта.

    {
      "decisions": [
        {"text": "Решение с необходимыми ограничениями", "timestamp": "HH:MM:SS"}
      ],
      "actions": [
        {"text": "Поручение; при необходимости — срок словами", "owner": "Полное имя, несколько имён или команда", "due": "YYYY-MM-DD"}
      ],
      "questions": [
        {"text": "Открытый вопрос или существенная неопределённость"}
      ],
      "summary": "Первый абзац раздела «Главный вывод» одной строкой"
    }

    Правила JSON:
    - Состав решений, задач и вопросов совпадает с разделами «Результаты и решения встречи», «Действия» и «Открытые вопросы и риски».
    - `timestamp` — таймкод реплики из расшифровки, в которой решение явно принято; если установить нельзя — `null`.
    - `owner` — как в таблице; если исполнитель не установлен — `null`.
    - `due` — только однозначная точная дата. Для интервала, ориентира или отсутствующего срока — `null`, а формулировка срока остаётся в `text`.
    - Для отсутствующих элементов — пустые массивы. Без комментариев внутри JSON.

    ## Перед выдачей проверь

    - прочитана ли вся встреча, включая финальные уточнения;
    - не попали ли предложения и заменённые варианты в решения;
    - подтверждаются ли имена, поручения и сроки источником;
    - нет ли в тексте идентификаторов, таймкодов и служебных пометок;
    - сохранены ли все обязательные разделы и их порядок;
    - валиден ли JSON и совпадает ли он с текстом документа.
    """
}
