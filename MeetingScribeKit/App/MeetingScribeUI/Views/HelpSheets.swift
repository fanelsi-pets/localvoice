import SwiftUI

/// Справка из меню Help (DESIGN.md §6): краткое руководство и инструкция по раздельным дорожкам Zoom.
struct HelpSheet: View {
  let topic: HelpTopic
  @Environment(\.dismiss) private var dismiss

  var body: some View {
    VStack(alignment: .leading, spacing: 12) {
      Text(topic.title).font(.title3)
      ScrollView {
        Text(body(for: topic))
          .frame(maxWidth: .infinity, alignment: .leading)
          .textSelection(.enabled)
      }
      HStack {
        Spacer()
        Button("Закрыть") { dismiss() }
          .keyboardShortcut(.defaultAction)
      }
    }
    .padding()
    .frame(minWidth: 460, minHeight: 320)
    .accessibilityElement(children: .contain)
    .accessibilityIdentifier("help.sheet")
  }

  private func body(for topic: HelpTopic) -> String {
    switch topic {
    case .guide:
      String(
        localized: """
          1. Перетащите в окно запись Zoom — файл video*.mp4, audio*.m4a или папку записи целиком.
          2. В диалоге импорта выберите проект, при желании укажите число участников и язык.
             «Авто, по каждому спикеру» — правильный выбор для смешанных русско-украинских встреч.
          3. Приложение обработает запись на этом Mac: подготовка аудио → разделение по голосам →
             определение языка → распознавание → сшивка. Прогресс с процентом, прогнозом и лентой
             распознанного виден в тулбаре, в строке боковой панели и на карточке встречи.
             Обработку можно отменить в любой момент, а окно — закрыть: работа продолжится.
          4. В инспекторе «Спикеры» подтвердите имена: голос сохранится в профиль человека («Люди»),
             и на следующих встречах он будет узнан автоматически (≥ 70 % сходства — сразу, 55–70 % —
             как предложение). Ошибки диаризации правятся там же: «Объединить с…», «Разделить по
             диапазону…», а у реплики — «Приписать спикеру…», «Разделить здесь», «Объединить с предыдущей».
          5. Экспорт: «Скопировать TranscribeFull» (⌘⇧C) или «Сохранить .md» (⌘E), а также SRT и JSON.
             Markdown содержит шапку, участников, транскрипт с таймкодами и готовый промпт для follow-up.
          """)
    case .zoomTracks:
      String(
        localized: """
          Имена спикеров получаются точнее всего, если Zoom записал отдельную дорожку на участника.

          В десктоп-клиенте Zoom: Settings → Recording → включите
          «Record a separate audio file for each participant».

          После следующей записи в папке встречи появится подпапка «Audio Record/» с файлами вида
          audio<Имя><цифры>.m4a — по одной дорожке на участника. Имена берутся прямо из имён файлов,
          диаризация не нужна.

          Папка записи лежит в ~/Documents/Zoom/<дата время> <название комнаты>/ и содержит общий трек
          audio*.m4a, видео video*.mp4, recording.conf и (если был чат) chat.txt.

          Перетащите папку записи целиком: приложение найдёт дорожки, предложит обработать их
          по отдельности (переключатель в диалоге импорта) и подставит имена участников. Видео из той же
          папки используется для распознавания подписей («Найти имена на видео» в инспекторе спикеров),
          chat.txt — как подсказки имён.
          """)
    }
  }
}
